"""Reproduce the COSMOS 2589 failure through the REAL PSIRENS code, and prove
each audit finding that can be proved offline.

Inputs are the two element sets Ash supplied on 17 November 2026: the UDL line
(SAFRAN-class, 127.9E) and the NorthStar line PSIRENS displayed (64.2E). Each
provider's history is generated by advancing ONLY the mean anomaly of its own
line at its own mean motion (two-body, no invention beyond that), sampled every
2 h, as a UDL /udl/elset response would carry it. Nothing below re-implements
PSIRENS: every number comes from the shipped modules.

Usage: PYTHONPATH=src python audits/2026-11-17-tle-provenance/prove.py

F4 (a CONFIRMED E-W event from the blend) is a FACT of the live system, read
from Ash's /api/events export; it is NOT reproduced here, because whether the
detector fires depends on how the two providers' samples interleave. That
dependence on timing, with no rule to stop it, is itself the finding.
"""
from __future__ import annotations

import tempfile
from datetime import datetime, timedelta, timezone

import httpx

from psirens.config import Config
from psirens.conjunction import build_satrec, tle_for
from psirens.events import Thresholds, detect
from psirens.main import _drift_block, _tracks_payload
from psirens.models import DataMode
from psirens.sources import UDLElsetSource
from psirens.store import Store
from psirens.tle import provenance_of

SAT = "64467"
GOOD = ("SAFRAN", "1 64467U 25131A   26321.41066406 -.00000076 +00000-0 -63064-4 0  0001",
        "2 64467   0.3274  86.4242 0007366  37.1819 208.6412  1.00265344000011")
BAD = ("NorthStar", "1 64467U 25131A   26321.35849668 +.00000000 +00000+0 +00000+0 0 99999",
       "2 64467   0.3270  86.3698 0006840  38.8569 124.4911  0.99642971005091")
REF = datetime(2026, 11, 17, 9, 0, tzinfo=timezone.utc)
RESULTS: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str) -> None:
    RESULTS.append((name, ok, detail))
    print(("PROVEN   " if ok else "NOT SHOWN") + f"  {name}: {detail}")


def _epoch_of(l1: str) -> datetime:
    yy, doy = int(l1[18:20]), float(l1[20:32])
    return datetime(2000 + yy, 1, 1, tzinfo=timezone.utc) + timedelta(days=doy - 1)


def rows_for(provider: str, l1: str, l2: str, start: datetime, end: datetime,
             marking: str | None = "U//PR-TEST", mode: str = "REAL") -> list[dict]:
    """UDL-shaped rows for one provider's line, every 2 h over [start, end]."""
    e0, n = _epoch_of(l1), float(l2[52:63])
    out, t = [], start
    while t <= end:
        days = (t - e0).total_seconds() / 86400.0
        row = {"satNo": SAT, "epoch": t.isoformat().replace("+00:00", "Z"),
               "inclination": float(l2[8:16]), "raan": float(l2[17:25]),
               "eccentricity": float("0." + l2[26:33]), "argOfPerigee": float(l2[34:42]),
               "meanAnomaly": (float(l2[43:51]) + 360.0 * n * days) % 360.0,
               "meanMotion": n, "bStar": 0.0, "source": provider, "dataMode": mode}
        if marking is not None:
            row["classificationMarking"] = marking
        out.append(row)
        t += timedelta(hours=2)
    return out


def ingest(rows: list[dict], data_dir: str) -> Store:
    cfg = Config(port=8080, allowed_origin="", team_token="", retention_days=90,
                 refresh_seconds=3600, lon_min=-180, lon_max=180, inc_min=0,
                 inc_max=15, max_samples_per_object=2000, demo_mode=False,
                 udl_enabled=True, udl_base_url="http://udl.invalid",
                 udl_elset_path="/udl/elset", udl_user="u", udl_password="p",
                 udl_target_field="tags", udl_epoch_param="epoch",
                 udl_accept="application/json", data_dir=data_dir,
                 scheduler_enabled=False)
    client = httpx.Client(transport=httpx.MockTransport(lambda r: httpx.Response(200, json=rows)))
    src = UDLElsetSource(cfg, client=client)
    store = Store(data_dir)
    store.merge_samples(src.fetch(REF - timedelta(hours=1), REF), retention_days=90,
                        max_samples=2000, now=REF)
    return store


def main() -> int:
    import logging
    logging.getLogger("httpx").setLevel(logging.WARNING)
    # Scenario A: both providers overlapping for two days (F1 to F3).
    da = tempfile.mkdtemp(prefix="psirens-audit-")
    rows = rows_for(*GOOD, REF - timedelta(days=4), REF)
    rows += rows_for(*BAD, REF - timedelta(days=2) + timedelta(minutes=37), REF)
    obj = ingest(rows, da).load()["objects"][SAT]
    lons = sorted({round(s["sub_lon_deg"]) for s in obj["samples"]})
    check("F1 two providers are merged into ONE track",
          min(lons) < 70 and max(lons) > 120,
          f"{len(obj['samples'])} samples under {SAT}, longitudes from {min(lons)} to {max(lons)} deg")
    check("F2 samples carry no provider",
          all("source" not in s for s in obj["samples"]),
          f"sample keys: {sorted(obj['samples'][0])}")
    pairs = [(datetime.fromisoformat(s["epoch"]), s["sub_lon_deg"]) for s in obj["samples"]]
    blk = _drift_block(pairs, None)
    shown = (f"{blk['drift_deg_per_day']:+.2f} deg/day at {blk['drift_residual_deg']:.1f} deg rms"
             if blk["drift_deg_per_day"] is not None else "null")
    check("F3 a drift rate is published from the blend, its residual never checked",
          blk["drift_deg_per_day"] is not None and blk["drift_residual_deg"] > 1.0,
          f"drift {shown} (the 127.9E line alone: -0.03 deg/day)")
    print("OBSERVED   F4 the blend is reported as a CONFIRMED manoeuvre: live export, "
          "64467 STARTED CONFIRMED z 9.7, -0.01 -> -16.32 deg/day (not reproduced offline)")
    # Scenario B: timing as the live export shows it (F5, F6). The 127.9E source
    # reports until 16 Nov ~20:00Z; NorthStar runs on to its 17 Nov 08:36Z epoch.
    d = tempfile.mkdtemp(prefix="psirens-audit-")
    rows = rows_for(*GOOD, REF - timedelta(days=4), datetime(2026, 11, 16, 20, 3, tzinfo=timezone.utc))
    rows += rows_for(*BAD, datetime(2026, 11, 15, 10, 0, tzinfo=timezone.utc),
                     datetime(2026, 11, 17, 8, 36, tzinfo=timezone.utc))
    store = ingest(rows, d)
    obj = store.load()["objects"][SAT]
    head = _tracks_payload(_cfg(d), store, "real",
                           {DataMode.REAL})["tracks"][0]["samples"][-1]
    check("F5 the plot head is whichever provider published last",
          head["sub_lon_deg"] < 70,
          f"head at {head['sub_lon_deg']:.2f} deg, epoch {head['epoch'][:16]}")
    el, lines, prov = tle_for(obj)
    check("F6 commercial-first selection serves the outlier provider",
          prov["source"] == "NorthStar",
          f"served {prov['source']} ({prov['source_class']}); SAFRAN classed "
          f"{provenance_of(obj['elset_candidates']['SAFRAN'], native=False)['source_class']}")
    # F7: an element set with NO marking is labelled U and offered for copy.
    d2 = tempfile.mkdtemp(prefix="psirens-audit-")
    s2 = ingest(rows_for(*GOOD, REF - timedelta(hours=6), REF, marking=None), d2)
    o2 = s2.load()["objects"][SAT]
    _, _, p2 = tle_for(o2)
    check("F7 a record with NO classification marking is served as U and copyable",
          o2["classification_marking"] == "U" and p2["copyable"] is True,
          f"track marking {o2['classification_marking']!r}, TLE marking "
          f"{p2['classification_marking']!r}, copyable {p2['copyable']}")
    # F8: no native line -> a reconstructed TLE with invented fields.
    _, rl, rp = tle_for(o2)
    check("F8 with no native line a TLE is RECONSTRUCTED, with invented fields",
          rp["native"] is False and rl is not None,
          f"line1 {rl[0] if rl else None!r}")
    # F9: missing elements are filled with 0.0 and still plotted.
    row = rows_for(*GOOD, REF, REF)[0]
    for k in ("meanAnomaly", "argOfPerigee", "raan", "eccentricity"):
        row.pop(k)
    d3 = tempfile.mkdtemp(prefix="psirens-audit-")
    o3 = ingest([row], d3).load()["objects"].get(SAT)
    check("F9 a row MISSING mean anomaly, perigee, RAAN and e is still plotted",
          o3 is not None,
          f"plotted at {o3['samples'][0]['sub_lon_deg']:.2f} deg from defaults of 0.0"
          if o3 else "rejected")
    # F10: an EXERCISE row for the same catalogue number lands in the REAL object.
    d4 = tempfile.mkdtemp(prefix="psirens-audit-")
    mix = rows_for(*GOOD, REF - timedelta(hours=6), REF - timedelta(hours=2))
    mix += rows_for("EXERCISE-CELL", GOOD[1], GOOD[2], REF, REF, mode="EXERCISE")
    o4 = ingest(mix, d4).load()["objects"][SAT]
    check("F10 data modes are merged per catalogue number, last pull labels the lot",
          len(o4["samples"]) == len(mix),
          f"{len(o4['samples'])} samples (REAL and EXERCISE) under one object labelled {o4['data_mode']}")
    # F11: the screen ignores the provider's ephemeris type and drag terms.
    el11 = dict(obj["elset_candidates"]["SAFRAN"], ephem_type=4, mean_motion_dot=1e-6)
    sat = build_satrec(el11)
    check("F11 the conjunction screen ignores ephemType and n-dot",
          sat.ephtype == 0 and sat.ndot == 0.0,
          f"record says ephemType 4, propagated as {sat.ephtype}; n-dot {sat.ndot}")
    # F12: a provider's newest fix is retained for ever and outranks fresher data.
    d5 = tempfile.mkdtemp(prefix="psirens-audit-")
    old = rows_for("NorthStar", GOOD[1], GOOD[2], REF - timedelta(days=60), REF - timedelta(days=60))
    store5 = ingest(old, d5)
    fresh = rows_for("18 SDS", GOOD[1], GOOD[2], REF, REF)
    client = httpx.Client(transport=httpx.MockTransport(lambda r: httpx.Response(200, json=fresh)))
    store5.merge_samples(UDLElsetSource(_cfg(d5), client=client).fetch(REF, REF), retention_days=90,
                         max_samples=2000, now=REF)
    _, _, p5 = tle_for(store5.load()["objects"][SAT])
    check("F12 a 60-day-old commercial fix outranks a fresh government one",
          p5["source"] == "NorthStar",
          f"served {p5['source']} epoch {p5['epoch'][:10]} over 18 SDS epoch {REF:%Y-%m-%d}")
    bad = [r for r in RESULTS if not r[1]]
    print(f"\n{len(RESULTS) - len(bad)} of {len(RESULTS)} findings reproduced through the shipped code")
    return 0 if not bad else 1


