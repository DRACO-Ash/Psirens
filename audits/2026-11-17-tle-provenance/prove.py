"""Reproduce the COSMOS 2589 failure through the REAL PSIRENS code, and prove
each audit finding that can be proved offline.

Inputs are the two element sets Ash supplied on 17 November 2026: the UDL line
(SAFRAN-class, 127.9E) and the NorthStar line PSIRENS displayed (64.2E). Each
provider's history is generated by advancing ONLY the mean anomaly of its own
line at its own mean motion (two-body, no invention beyond that), sampled every
2 h, as a UDL /udl/elset response would carry it. Nothing below re-implements
PSIRENS: every number comes from the shipped modules.

Each finding prints REPRODUCES or FIXED against the code it runs on. Against
1.7.3 every offline finding reproduced; 1.7.4 (Ash's three rules) closes F2,
F7, F8, F9, F10, F11 and F13 and leaves the rest for the next change.

Usage: PYTHONPATH=src python audits/2026-11-17-tle-provenance/prove.py

F4 (a CONFIRMED E-W event from the blend) is a FACT of the live system, read
from Ash's /api/events export; it is NOT reproduced here, because whether the
detector fires depends on how the two providers' samples interleave. That
dependence on timing, with no rule to stop it, is itself the finding.
"""
from __future__ import annotations

